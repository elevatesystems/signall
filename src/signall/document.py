"""Classify a PDF and describe its signature fields."""
from __future__ import annotations

import enum
from dataclasses import dataclass, field

from pyhanko.sign.fields import enumerate_sig_fields

from signall.pdf import get as pget, open_reader
from signall.xfa import SignatureField, Template, XfaPackets


class Kind(enum.Enum):
    PLAIN = "plain"                 # no form at all
    ACROFORM = "acroform"           # ordinary interactive form
    STATIC_XFA = "static-xfa"       # XFA with a complete AcroForm fallback
    DYNAMIC_XFA = "dynamic-xfa"     # XFA only; pages are generated by the viewer

    @property
    def label(self) -> str:
        return {
            Kind.PLAIN: "PDF without form fields",
            Kind.ACROFORM: "PDF form",
            Kind.STATIC_XFA: "XFA form (static)",
            Kind.DYNAMIC_XFA: "XFA form (dynamic)",
        }[self]


@dataclass
class FieldInfo:
    name: str
    signed: bool
    signer: str | None = None
    signing_time: str | None = None
    page: int | None = None


@dataclass
class DocumentInfo:
    kind: Kind
    page_count: int
    encrypted: bool
    usage_rights: bool              # Adobe Reader extensions (/Perms /UR3)
    title: str | None
    signature_fields: list[FieldInfo] = field(default_factory=list)
    xfa_signature_fields: list[SignatureField] = field(default_factory=list)
    revisions: int = 1

    @property
    def unsigned_fields(self) -> list[str]:
        signed = {f.name for f in self.signature_fields if f.signed}
        names = [f.som for f in self.xfa_signature_fields] or [f.name for f in self.signature_fields]
        return [n for n in names if n not in signed]


def inspect(data: bytes) -> DocumentInfo:
    reader = open_reader(data)
    root = reader.root
    packets = XfaPackets.from_root(root)
    acroform = pget(root, "/AcroForm")
    has_fields = acroform is not None and len(pget(acroform, "/Fields", [])) > 0

    if packets is not None and bool(pget(root, "/NeedsRendering", False)):
        kind = Kind.DYNAMIC_XFA
    elif packets is not None:
        kind = Kind.STATIC_XFA
    elif has_fields:
        kind = Kind.ACROFORM
    else:
        kind = Kind.PLAIN

    perms = pget(root, "/Perms")
    info = pget(reader.trailer, "/Info")
    title = None
    if info is not None:
        title_obj = pget(info, "/Title")
        title = str(title_obj) if title_obj is not None else None

    fields: list[FieldInfo] = []
    for fq_name, value, field_ref in enumerate_sig_fields(reader, filled_status=None):
        signer = when = None
        if value is not None:
            value = value.get_object()
            raw_name = pget(value, "/Name")
            signer = str(raw_name) if raw_name is not None else None
            raw_time = pget(value, "/M")
            when = str(raw_time) if raw_time is not None else None
        fields.append(FieldInfo(name=fq_name, signed=value is not None, signer=signer, signing_time=when))

    xfa_fields: list[SignatureField] = []
    if packets is not None:
        template = packets.get("template")
        if template:
            xfa_fields = Template(template).signature_fields()

    return DocumentInfo(
        kind=kind,
        page_count=int(pget(root["/Pages"], "/Count", 0)),
        encrypted=reader.encrypted,
        usage_rights=perms is not None and "/UR3" in perms,
        title=title,
        signature_fields=fields,
        xfa_signature_fields=xfa_fields,
        revisions=reader.xrefs.total_revisions,
    )


def is_pure_xfa_layout(data: bytes) -> bool:
    """True if viewers will lay the document out from XFA alone (no widgets yet)."""
    reader = open_reader(data)
    acroform = pget(reader.root, "/AcroForm")
    return bool(pget(reader.root, "/NeedsRendering", False)) and (
        acroform is None or len(pget(acroform, "/Fields", [])) == 0
    )


__all__ = ["DocumentInfo", "FieldInfo", "Kind", "inspect", "is_pure_xfa_layout"]
